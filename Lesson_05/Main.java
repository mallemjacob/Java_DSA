public class Main {
    public static void main(String[] args) {
        String[] things = {"apples", "baboons", "cribs", "dulcimers", "cucumbers", "potatoes"};

        for (String thing : things) {
            System.out.println("Here's a thing: " + thing);
        }
    }
}

// O(N)
// O(1)
// O(log N)
